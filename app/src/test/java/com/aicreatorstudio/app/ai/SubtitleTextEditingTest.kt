package com.aicreatorstudio.app.ai

import com.aicreatorstudio.app.db.EditorStateJson
import com.aicreatorstudio.app.model.PersianFont
import com.aicreatorstudio.app.model.TextOverlay
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import java.util.UUID

/**
 * PHASE B3 — JVM unit tests for the subtitle text-editing
 * invariants.
 *
 * The brief is explicit: "Do NOT recalculate timestamps based on
 * text length." The ViewModel's `updateTextOverlay(id, newText)`
 * uses `overlay.copy(text = newText)` which guarantees this; the
 * tests below lock the contract end-to-end including the save /
 * reopen round-trip through the B2 persistence codec.
 */
class SubtitleTextEditingTest {

    @Test
    fun `editing text changes only the text - id, start, end, words, font all preserved`() {
        val original = makeAiSubtitle(
            text = "این یک تست است",
            startMs = 1_240L,
            endMs = 4_080L,
            words = listOf(
                makeWord("این", 1_240L, 2_100L),
                makeWord("یک", 2_200L, 2_800L),
                makeWord("تست", 2_900L, 3_500L),
                makeWord("است", 3_600L, 4_080L)
            )
        )
        val edited = original.copy(text = "این یک تست جدید است")
        // Only text changes; everything else is preserved bit-for-bit.
        assertEquals("id must be preserved", original.id, edited.id)
        assertEquals("startTimeMs must be preserved", original.startTimeMs, edited.startTimeMs)
        assertEquals("endTimeMs must be preserved", original.endTimeMs, edited.endTimeMs)
        assertEquals("words.size must be preserved", original.words.size, edited.words.size)
        for (i in original.words.indices) {
            assertEquals(
                "word[$i].id preserved",
                original.words[i].id, edited.words[i].id
            )
            assertEquals(
                "word[$i].text preserved (Whisper's word text must not " +
                    "follow user edits to the segment text)",
                original.words[i].text, edited.words[i].text
            )
            assertEquals(
                "word[$i].startTimeMs preserved",
                original.words[i].startTimeMs, edited.words[i].startTimeMs
            )
            assertEquals(
                "word[$i].endTimeMs preserved",
                original.words[i].endTimeMs, edited.words[i].endTimeMs
            )
        }
        assertEquals("fontFamily preserved", original.fontFamily, edited.fontFamily)
        assertEquals("karaokeEnabled preserved", original.karaokeEnabled, edited.karaokeEnabled)
    }

    @Test
    fun `editing the text does not move the active-word pointer at any playhead position`() {
        val original = makeAiSubtitle(
            text = "یک دو سه",
            startMs = 1_000L,
            endMs = 4_000L,
            words = listOf(
                makeWord("یک", 1_000L, 2_000L),
                makeWord("دو", 2_000L, 3_000L),
                makeWord("سه", 3_000L, 4_000L)
            )
        )
        val edited = original.copy(text = "X Y Z W V")
        // The word list was generated by whisper.cpp and pinned to
        // real acoustic timestamps; the user-edited text must NOT
        // re-time the karaoke highlight. The active-word pointer is
        // computed from `words`, which is unchanged.
        for (pos in 1_000L..4_000L step 250L) {
            val origActive = original.words.firstOrNull { it.isActiveAt(pos) }
            val editActive = edited.words.firstOrNull { it.isActiveAt(pos) }
            assertEquals(
                "active word at $pos ms must be the same before and after edit",
                origActive?.id, editActive?.id
            )
        }
    }

    @Test
    fun `edited subtitle survives a save-reopen round-trip with the edited text and original timing`() {
        val original = makeAiSubtitle(
            text = "سلام دنیا",
            startMs = 1_240L,
            endMs = 4_080L,
            words = listOf(
                makeWord("سلام", 1_240L, 2_100L),
                makeWord("دنیا", 2_500L, 4_080L)
            )
        )
        val edited = original.copy(text = "سلام دنیای جدید")
        // Save (real codec) + reopen (real codec).
        val json = EditorStateJson.textOverlaysToJson(listOf(edited))
        val restored = EditorStateJson.textOverlaysFromJson(json)
        assertEquals(1, restored.size)
        val r = restored.first()
        // Edited text survives.
        assertEquals("edited text preserved across save/reopen", "سلام دنیای جدید", r.text)
        // Original timing preserved.
        assertEquals("startTimeMs preserved", original.startTimeMs, r.startTimeMs)
        assertEquals("endTimeMs preserved", original.endTimeMs, r.endTimeMs)
        // Per-word timing also preserved (the karaoke highlight
        // continues to work after reopen).
        assertEquals(original.words.size, r.words.size)
        for (i in original.words.indices) {
            assertEquals(original.words[i].id, r.words[i].id)
            assertEquals(original.words[i].text, r.words[i].text)
            assertEquals(original.words[i].startTimeMs, r.words[i].startTimeMs)
            assertEquals(original.words[i].endTimeMs, r.words[i].endTimeMs)
        }
    }

    @Test
    fun `empty text edit is allowed (preserves id and timestamps) but the resulting text is blank`() {
        // The brief does not require us to refuse blank edits; the
        // user may want to clear the caption while keeping the
        // timing. The test pins the contract: no fields other than
        // text change, the resulting text is "".
        val original = makeAiSubtitle(
            text = "anything",
            startMs = 500L,
            endMs = 1_500L,
            words = listOf(makeWord("anything", 500L, 1_500L))
        )
        val edited = original.copy(text = "")
        assertEquals("", edited.text)
        assertEquals(original.id, edited.id)
        assertEquals(original.startTimeMs, edited.startTimeMs)
        assertEquals(original.endTimeMs, edited.endTimeMs)
        assertEquals(original.words.size, edited.words.size)
    }

    @Test
    fun `persian unicode including ZWNJ and arabic-indic digits is preserved across edit and round-trip`() {
        val original = makeAiSubtitle(
            text = "گرافیک ۵",
            startMs = 0L,
            endMs = 1_500L,
            words = listOf(makeWord("گرافیک", 0L, 800L), makeWord("۵", 800L, 1_500L))
        )
        val edited = original.copy(text = "گرافیک ۵ - ویرایش شده")
        val json = EditorStateJson.textOverlaysToJson(listOf(edited))
        val restored = EditorStateJson.textOverlaysFromJson(json)
        assertEquals("edited Persian text with ZWNJ and Arabic-Indic digits " +
            "must round-trip identically", "گرافیک ۵ - ویرایش شده", restored.first().text)
        // Per-word Persian preserved too.
        assertEquals("گرافیک", restored.first().words[0].text)
        assertEquals("۵", restored.first().words[1].text)
    }

    @Test
    fun `re-editing an already-edited subtitle still does not change the original id or timestamps`() {
        val original = makeAiSubtitle(
            text = "اول",
            startMs = 100L,
            endMs = 200L,
            words = listOf(makeWord("اول", 100L, 200L))
        )
        val edit1 = original.copy(text = "دوم")
        val edit2 = edit1.copy(text = "سوم")
        val edit3 = edit2.copy(text = "")
        // After three re-edits, only the text moves.
        assertEquals(original.id, edit3.id)
        assertEquals(original.startTimeMs, edit3.startTimeMs)
        assertEquals(original.endTimeMs, edit3.endTimeMs)
        assertEquals("", edit3.text)
        assertNotEquals("text is actually different from the original", original.text, edit3.text)
    }

    // ---- Helpers ----

    private fun makeAiSubtitle(
        text: String,
        startMs: Long,
        endMs: Long,
        words: List<TranscribedWord>
    ) = TextOverlay(
        id = UUID.randomUUID().toString(),
        text = text,
        startTimeMs = startMs,
        endTimeMs = endMs,
        fontFamily = PersianFont.VAZIR.name,
        words = words,
        karaokeEnabled = true
    )

    private fun makeWord(
        text: String,
        startMs: Long,
        endMs: Long
    ) = TranscribedWord(
        id = UUID.randomUUID().toString(),
        text = text,
        startTimeMs = startMs,
        endTimeMs = endMs,
        confidence = 0.9f
    )
}
