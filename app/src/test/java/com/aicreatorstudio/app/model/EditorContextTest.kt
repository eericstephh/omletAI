package com.aicreatorstudio.app.model

import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Unit tests for [resolveEditorContext] — the single derivation that drives
 * the editor's contextual toolbar.
 *
 * Regression guard: before the 2026-09-28 IA audit the dock was
 * context-blind (it rendered the same 12 chips in every selection state), and
 * `SubtitleDelegate.selectTextOverlay` did not clear the other two selection
 * ids, so a text tap could leave a video clip selected underneath. Both the
 * priority ordering here and the mutual-exclusion invariant asserted by
 * `SelectionExclusivityTest` exist so that can't silently return.
 */
class EditorContextTest {

    // ---- the four clean states ----

    @Test
    fun `nothing selected resolves to ROOT`() {
        assertEquals(
            EditorContext.ROOT,
            resolveEditorContext(
                selectedClipId = null,
                selectedAudioClipId = null,
                selectedTextId = null
            )
        )
    }

    @Test
    fun `only a video clip selected resolves to CLIP_SELECTED`() {
        assertEquals(
            EditorContext.CLIP_SELECTED,
            resolveEditorContext(
                selectedClipId = "clip-1",
                selectedAudioClipId = null,
                selectedTextId = null
            )
        )
    }

    @Test
    fun `only an audio clip selected resolves to AUDIO_SELECTED`() {
        assertEquals(
            EditorContext.AUDIO_SELECTED,
            resolveEditorContext(
                selectedClipId = null,
                selectedAudioClipId = "audio-1",
                selectedTextId = null
            )
        )
    }

    @Test
    fun `only a text overlay selected resolves to TEXT_SELECTED`() {
        assertEquals(
            EditorContext.TEXT_SELECTED,
            resolveEditorContext(
                selectedClipId = null,
                selectedAudioClipId = null,
                selectedTextId = "text-1"
            )
        )
    }

    // ---- priority ordering (defensive; the invariant should prevent these) ----

    @Test
    fun `text wins over a video clip`() {
        assertEquals(
            EditorContext.TEXT_SELECTED,
            resolveEditorContext("clip-1", null, "text-1")
        )
    }

    @Test
    fun `text wins over an audio clip`() {
        assertEquals(
            EditorContext.TEXT_SELECTED,
            resolveEditorContext(null, "audio-1", "text-1")
        )
    }

    @Test
    fun `text wins when all three are set`() {
        assertEquals(
            EditorContext.TEXT_SELECTED,
            resolveEditorContext("clip-1", "audio-1", "text-1")
        )
    }

    @Test
    fun `audio wins over a video clip`() {
        assertEquals(
            EditorContext.AUDIO_SELECTED,
            resolveEditorContext("clip-1", "audio-1", null)
        )
    }

    @Test
    fun `audio wins over a video clip when no text is selected`() {
        // Same as above but spelled out for the "which of the two non-text
        // ids wins" contract, which is the audio > clip half of the rule.
        assertEquals(
            EditorContext.AUDIO_SELECTED,
            resolveEditorContext(
                selectedClipId = "clip-1",
                selectedAudioClipId = "audio-1",
                selectedTextId = null
            )
        )
    }

    // ---- the derivation is total: every id permutation is covered ----

    @Test
    fun `all eight id permutations resolve to exactly one context`() {
        val ids = listOf<String?>(null, "set")
        val seen = mutableSetOf<EditorContext>()
        for (clip in ids) {
            for (audio in ids) {
                for (text in ids) {
                    val context = resolveEditorContext(clip, audio, text)
                    seen += context
                    val expected = when {
                        text != null -> EditorContext.TEXT_SELECTED
                        audio != null -> EditorContext.AUDIO_SELECTED
                        clip != null -> EditorContext.CLIP_SELECTED
                        else -> EditorContext.ROOT
                    }
                    assertEquals(
                        "clip=$clip audio=$audio text=$text",
                        expected,
                        context
                    )
                }
            }
        }
        // Every branch of the resolver is actually reachable.
        assertEquals(EditorContext.entries.toSet(), seen)
    }

    // ---- a non-null id counts as selected, even if blank ----

    @Test
    fun `an empty-string id still counts as a selection`() {
        // Ids are generated by the model and are never blank in practice, but
        // the resolver keys off null-ness only — it must not silently fall
        // back to ROOT for a non-null id, which would make the toolbar
        // disagree with the canvas highlight.
        assertEquals(
            EditorContext.CLIP_SELECTED,
            resolveEditorContext("", null, null)
        )
    }

    // ---- adjacency drives the conditional Transitions chip (Q7) ----

    private fun clip(id: String, startMs: Long, durationMs: Long) = VideoClip(
        id = id,
        uri = "file:///$id.mp4",
        fileName = "$id.mp4",
        durationMs = durationMs,
        width = 1080,
        height = 1920,
        fileSizeBytes = 0L,
        importedAtEpochMillis = 0L,
        timelineStartMs = startMs
    )

    @Test
    fun `a lone clip has no neighbour`() {
        assertFalse(hasAdjacentClip(listOf(clip("a", 0L, 1000L)), "a"))
    }

    @Test
    fun `butt-joined clips count as adjacent`() {
        val clips = listOf(clip("a", 0L, 1000L), clip("b", 1000L, 1000L))
        assertTrue(hasAdjacentClip(clips, "a"))
        assertTrue(hasAdjacentClip(clips, "b"))
    }

    @Test
    fun `clips inside the timeline tolerance count as adjacent`() {
        // Matches the timeline's transition-handle tolerance (-80..80 ms).
        val clips = listOf(clip("a", 0L, 1000L), clip("b", 1060L, 1000L))
        assertTrue(hasAdjacentClip(clips, "a"))
    }

    @Test
    fun `clips separated by a real gap are not adjacent`() {
        val clips = listOf(clip("a", 0L, 1000L), clip("b", 1500L, 1000L))
        assertFalse(hasAdjacentClip(clips, "a"))
        assertFalse(hasAdjacentClip(clips, "b"))
    }

    @Test
    fun `a gap larger than the tolerance is not adjacent`() {
        val clips = listOf(clip("a", 0L, 1000L), clip("b", 1100L, 1000L))
        assertFalse(hasAdjacentClip(clips, "a"))
    }

    @Test
    fun `the middle clip of three is adjacent`() {
        val clips = listOf(
            clip("a", 0L, 1000L),
            clip("b", 1000L, 1000L),
            clip("c", 2000L, 1000L)
        )
        assertTrue(hasAdjacentClip(clips, "b"))
        // The outer clips each touch one neighbour.
        assertTrue(hasAdjacentClip(clips, "a"))
        assertTrue(hasAdjacentClip(clips, "c"))
    }

    @Test
    fun `an unknown or null clip id has no neighbour`() {
        val clips = listOf(clip("a", 0L, 1000L))
        assertFalse(hasAdjacentClip(clips, null))
        assertFalse(hasAdjacentClip(clips, "missing"))
        assertFalse(hasAdjacentClip(emptyList(), "a"))
    }
}
